"""Robust DXF loading from uploaded bytes; supports AutoCAD DXF with 310 binary chunks.

Only DXF, not DWG. Limit input size and geometry counts to keep interactive UI responsive.
"""
from __future__ import annotations
import os
import tempfile
import ezdxf
from ezdxf import recover

MAX_DXF_BYTES=40*1024*1024

def open_dxf(content: bytes):
    if not content or len(content)>MAX_DXF_BYTES:
        raise ValueError('DXF leer oder zu groß (max. 40 MB).')
    # Writing original bytes is essential: read(StringIO(...)) can reject valid ASCII
    # DXF containing extended 310 binary data chunks generated by AutoCAD.
    path=None
    try:
        with tempfile.NamedTemporaryFile(suffix='.dxf',delete=False) as f:
            f.write(content);path=f.name
        try:
            doc=ezdxf.readfile(path)
        except (ezdxf.DXFStructureError,ezdxf.DXFError):
            doc,auditor=recover.readfile(path)
            if auditor.has_errors:
                raise ValueError('DXF enthält nicht rekonstruierbare Strukturfehler; bitte in AutoCAD AUDIT verwenden.')
        if len(doc.modelspace())>150_000:
            raise ValueError('Zu viele DXF-Objekte (max. 150000). Zeichnung bereinigen.')
        return doc
    except Exception as exc:
        raise ValueError(f'DXF-Einlesefehler: {exc}') from exc
    finally:
        if path and os.path.exists(path): os.unlink(path)
